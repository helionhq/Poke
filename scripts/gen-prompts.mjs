#!/usr/bin/env node
// Bundles packages/agent-core/prompts/*.md into src/prompts.generated.ts (agent-core stays free of
// fs so it runs anywhere). Run `pnpm gen:prompts` after editing a prompt; a test checks it's in sync.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "agent-core");
export function renderGenerated() {
  const files = readdirSync(join(root, "prompts"))
    .filter((f) => f.endsWith(".md"))
    .sort();
  const entries = files.map((f) => {
    const name = f.replace(/\.md$/, "");
    const text = readFileSync(join(root, "prompts", f), "utf8").replace(/\r\n/g, "\n");
    return `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`;
  });
  return `// Generated by scripts/gen-prompts.mjs from packages/agent-core/prompts/*.md. Do not edit.\nexport const PROMPT_SOURCES = {\n${entries.join("\n")}\n} as const;\n\nexport type PromptName = keyof typeof PROMPT_SOURCES;\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "src", "prompts.generated.ts"), renderGenerated());
  console.log("prompts.generated.ts updated");
}
